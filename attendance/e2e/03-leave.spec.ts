import { expect, test } from '@playwright/test'
import { login, TINY_PNG } from './helpers'

test.describe('Stage 3: leave', () => {
  test('Kavitha applies with a document; days follow her Wed-Sun roster', async ({ page }) => {
    await login(page, 'kavitha@yam.test')
    await page.goto('/requests')
    await page.getByRole('link', { name: 'Apply for leave' }).click()
    await page.getByLabel('Leave type').selectOption({ label: 'Hospitalization Leave' })
    await expect(page.getByText('Please attach your medical certificate')).toBeVisible()
    await page.getByLabel('Start date').fill('2026-10-12')
    await page.getByLabel('End date').fill('2026-10-16')
    await expect(page.getByText('This will use 3 working days')).toBeVisible()
    await expect(page.getByLabel('Full or half day')).toHaveCount(0) // multi-day: no half day option
    await page.getByLabel('Reason').fill('Surgery recovery')
    await page.getByTestId('file-input').setInputFiles({ name: 'mc.png', mimeType: 'image/png', buffer: TINY_PNG })
    await expect(page.getByAltText('Attachment preview')).toBeVisible()
    await page.getByRole('button', { name: 'Submit for approval' }).click()
    await expect(page.getByText('Pending approval')).toBeVisible()
    await expect(page.getByText('Siti Aminah Yusof')).toBeVisible()
    await expect(page.getByText('3 working days')).toBeVisible()
    await expect(page.getByRole('button', { name: /View attachment/ })).toBeVisible()
  })

  test('weekend-only dates need no leave; drafts can be saved, edited and deleted', async ({ page }) => {
    await login(page, 'farid@yam.test')
    await page.goto('/leave/new')
    await page.getByLabel('Leave type').selectOption({ label: 'Annual Leave' })
    await page.getByLabel('Start date').fill('2026-10-17')
    await page.getByLabel('End date').fill('2026-10-18')
    await expect(page.getByText(/all off days or public holidays/)).toBeVisible()
    await page.getByRole('button', { name: 'Submit for approval' }).click()
    await expect(page.getByRole('alert')).toContainText('no leave is needed')

    await page.getByLabel('Start date').fill('2026-10-19')
    await page.getByLabel('End date').fill('2026-10-19')
    await page.getByLabel('Full or half day').selectOption('half_am')
    await expect(page.getByText('This will use 0.5 working days')).toBeVisible()
    await page.getByRole('button', { name: 'Save draft' }).click()
    await expect(page).toHaveURL(/\/leave$/)
    const draft = page.locator('.list-item', { hasText: 'Mon, 19 Oct' })
    await expect(draft).toContainText('Draft')
    await draft.click()
    await expect(page.getByRole('heading', { name: 'Edit leave draft' })).toBeVisible()
    page.once('dialog', (d) => d.accept())
    await page.getByRole('button', { name: 'Delete draft' }).click()
    await expect(page.locator('.list-item', { hasText: 'Mon, 19 Oct' })).toHaveCount(0)
  })

  test('leave draft saved offline syncs when back online', async ({ page, context }) => {
    await login(page, 'farid@yam.test')
    await page.goto('/leave/new')
    await page.getByLabel('Leave type').selectOption({ label: 'Compassionate Leave' })
    await page.getByLabel('Start date').fill('2026-10-21')
    await page.getByLabel('End date').fill('2026-10-21')
    await context.setOffline(true)
    await expect(page.getByTestId('syncbar')).toContainText('Offline')
    await expect(page.getByRole('button', { name: 'Submit for approval' })).toBeDisabled()
    await page.getByRole('button', { name: 'Save draft' }).click()
    await expect(page).toHaveURL(/\/leave$/)
    await expect(page.getByTestId('syncbar')).toContainText('Offline, 1 entry waiting to sync')
    await expect(page.locator('.list-item', { hasText: 'Wed, 21 Oct' })).toContainText('waiting to sync')
    await context.setOffline(false)
    await expect(page.getByTestId('syncbar')).toHaveCount(0, { timeout: 15000 })
    await page.reload()
    await expect(page.locator('.list-item', { hasText: 'Wed, 21 Oct' })).toContainText('Draft')
    await expect(page.locator('.list-item', { hasText: 'Wed, 21 Oct' })).not.toContainText('waiting to sync')
    // submit it now that we are online
    await page.locator('.list-item', { hasText: 'Wed, 21 Oct' }).click()
    await page.getByRole('button', { name: 'Submit for approval' }).click()
    await expect(page.getByText('Pending approval')).toBeVisible()
  })

  test('approved leave shows as On Leave in history and on the clock screen', async ({ page }) => {
    await login(page, 'kavitha@yam.test')
    await page.goto('/history?view=month&date=2026-09-01')
    await expect(page.locator('.list-item', { hasText: 'Sat, 5 Sept' })).toContainText('On Leave (Hospitalization Leave)')
    await expect(page.locator('.list-item', { hasText: 'Mon, 7 Sept' })).toContainText('Off day')
    await page.goto('/leave')
    await expect(page.locator('.list-item', { hasText: '5 Sept' })).toContainText('Approved')
  })
})
